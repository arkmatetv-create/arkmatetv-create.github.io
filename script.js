const TOUR_LINKS = {
  en: 'promo_video_en.html',
  tr: 'promo_video_tr.html'
};

function detectLanguage() {
  const stored = localStorage.getItem('arkmate-site-lang');
  return stored === 'tr' ? 'tr' : 'en';
}

function setLanguage(lang) {
  const strings = translations[lang] || translations.en;
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.dataset.i18n;
    if (strings[key]) node.textContent = strings[key];
  });

  const select = document.getElementById('language-select');
  if (select) select.value = lang;
  localStorage.setItem('arkmate-site-lang', lang);

  ['tour-link', 'hero-tour-link', 'review-tour-link'].forEach((id) => {
    const link = document.getElementById(id);
    if (link) link.href = TOUR_LINKS[lang] || TOUR_LINKS.en;
  });
}

const initialLanguage = detectLanguage();
setLanguage(initialLanguage);

document.getElementById('language-select')?.addEventListener('change', (event) => {
  setLanguage(event.target.value);
});
